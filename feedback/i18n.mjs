export function translate(text, language) {
  if (language !== "ja") return text;
  const key = text.trim().replace(/\s+/g, " ");
  if (JA[key]) return text.match(/^\s*/)[0] + JA[key] + text.match(/\s*$/)[0];
  if (key.endsWith(" *") && JA[key.slice(0, -2)])
    return JA[key.slice(0, -2)] + " *";
  let match = /^Uploading video part (\d+) of (\d+)…$/.exec(key);
  if (match)
    return `動画をアップロードしています…（${match[1]} / ${match[2]}）`;
  match = /^(.* · [\d.]+ MB · )(\d+) seconds$/.exec(key);
  if (match) return `${match[1]}${match[2]}秒`;
  match = /^Please shorten your answer to (\d+) characters\.$/.exec(key);
  if (match) return `${match[1]}文字以内でご入力ください。`;
  const suffix = " Your written feedback is saved.";
  if (key.endsWith(suffix))
    return (
      translate(key.slice(0, -suffix.length), language) +
      " " +
      JA[suffix.trim()]
    );
  return text;
}
let language = "en";
export const getLanguage = () => language;
export function setupLanguage() {
  let saved;
  try {
    saved = localStorage.getItem("sunveda-feedback-language");
  } catch {}
  const query = new URLSearchParams(location.search).get("lang");
  language = ["en", "ja"].includes(query)
    ? query
    : ["en", "ja"].includes(saved)
      ? saved
      : navigator.language.startsWith("ja")
        ? "ja"
        : "en";
  const label = document.createElement("label");
  label.className = "language-switch";
  label.textContent = "Language / 言語 ";
  const select = document.createElement("select");
  select.setAttribute("aria-label", "Language / 言語");
  for (const [value, text] of [
    ["en", "English"],
    ["ja", "日本語"],
  ]) {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = text;
    select.append(option);
  }
  select.value = language;
  label.append(select);
  document.querySelector(".topbar").append(label);
  const sources = new WeakMap();
  function update(node, attribute) {
    const value = attribute ? node.getAttribute(attribute) : node.nodeValue;
    if (!value?.trim()) return;
    const key = attribute || "text";
    const records = sources.get(node) || {};
    const previous = records[key];
    const original =
      previous && previous.output === value ? previous.original : value;
    const output = translate(original, language);
    records[key] = { original, output };
    sources.set(node, records);
    if (output !== value) {
      if (attribute) node.setAttribute(attribute, output);
      else node.nodeValue = output;
    }
  }
  function apply() {
    observer.disconnect();
    document.documentElement.lang = language;
    const walk = document.createTreeWalker(
      document.documentElement,
      NodeFilter.SHOW_TEXT,
    );
    while (walk.nextNode()) {
      const node = walk.currentNode;
      if (
        !node.parentElement.closest(
          "script,style,textarea,select,.language-switch",
        )
      )
        update(node);
    }
    document.querySelectorAll("[placeholder],[aria-label]").forEach((node) => {
      if (node.closest(".language-switch")) return;
      for (const attr of ["placeholder", "aria-label"])
        if (node.hasAttribute(attr)) update(node, attr);
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "aria-label"],
    });
  }
  const observer = new MutationObserver(apply);
  select.onchange = () => {
    language = select.value;
    try {
      localStorage.setItem("sunveda-feedback-language", language);
    } catch {}
    const url = new URL(location.href);
    url.searchParams.set("lang", language);
    history.replaceState(null, "", url);
    apply();
    window.dispatchEvent(new Event("feedback-language-change"));
  };
  apply();
}
